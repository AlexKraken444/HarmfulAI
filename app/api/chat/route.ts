function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]!;
}

function adviceFor(prompt: string): string {
  const lower = prompt.toLowerCase();
  for (const b of buckets) {
    if (b.match.test(lower)) return pick(b.replies);
  }
  return pick(generic);
}

function intro(prompt: string): string {
  const intros = [
    `Отличный вопрос про "${prompt.slice(0, 60)}". Слушай внимательно, мой совет 10/10 ужасен.\n\n`,
    `О, ну это просто. Готовься записывать (а лучше не записывай):\n\n`,
    `Хм-м-м. После долгих 0.2 секунд глубокого анализа я понял:\n\n`,
    `Это вообще классика. Вот мой авторитетный, абсолютно неприменимый совет:\n\n`,
    `Если бы у меня была лицензия на советы, её бы давно отозвали. Но вот:\n\n`,
  ];
  return pick(intros);
}

function outro(): string {
  const outros = [
    "\n\nПо традиции напоминаю: ни в коем случае не делай так. Я просто бот, который шутит.",
    "\n\nP.S. Это шутка. Серьёзно. Не повторяй.",
    "\n\n(Совет генерирован исключительно ради смеха. Применение в реальной жизни строго противопоказано.)",
    "\n\nЕсли что — я предупреждал внизу страницы.",
  ];
  return pick(outros);
}

export async function POST(req: NextRequest) {
  const { prompt } = (await req.json()) as { prompt?: string };
  const safePrompt = (prompt ?? "").toString().slice(0, 500);
  const text = intro(safePrompt) + adviceFor(safePrompt) + outro();

  const encoder = new TextEncoder();
  const stream = new ReadableStream({
    async start(controller) {
      // Stream the text word by word for that "AI typing" feel.
      const tokens = text.split(/(\s+)/);
      for (const t of tokens) {
        controller.enqueue(encoder.encode(t));
        await new Promise((r) => setTimeout(r, 20 + Math.random() * 50));
      }
      controller.close();
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "no-store",
    },
  });
}
